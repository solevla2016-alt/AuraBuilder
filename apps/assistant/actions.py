"""Что умеет помощник и сколько стоит каждое действие.

Список действий — данные, а не ветвления в API: интерфейс получает
названия, цену и подсказку одним ответом и не держит вторую копию.
Новое действие появляется здесь, а не в трёх местах сразу.

Цена в кредитах, а не в токенах: человеку нужно понимать стоимость до
нажатия кнопки, а не после счёта от провайдера. Разные цены отражают
разный объём работы — разбор проекта читает только сводку, генерация
плана строит структуру.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Action:
    code: str
    title: str
    description: str
    cost: int
    placeholder: str
    needs_description: bool
    #: Требование к модели. Держится рядом с действием, потому что
    #: меняется вместе с ним, а не вместе с провайдером.
    instruction: str


ACTIONS: dict[str, Action] = {
    'page_outline': Action(
        code='page_outline',
        title='План страницы',
        description='Опишите, какой должна быть страница, — помощник '
                    'предложит порядок секций и модули из каталога.',
        cost=3,
        placeholder='Например: лендинг студии ремонта с преимуществами, '
                    'этапами работы, отзывами и формой заявки.',
        needs_description=True,
        instruction=(
            'Составь план страницы по описанию. Верни JSON-объект с полями '
            'summary (одна фраза) и items — массив секций сверху вниз. '
            'В каждом элементе: title — название секции, detail — зачем '
            'она нужна, module — идентификатор модуля из каталога '
            '(например section.hero, section.feature, promo.pricing, '
            'action.form, section.footer). Не выдумывай модули, которых '
            'нет в каталоге. Не пиши тексты для сайта.'
        ),
    ),
    'data_schema': Action(
        code='data_schema',
        title='Схема данных',
        description='Опишите задачу — помощник предложит поля источника '
                    'данных с типами и обязательностью.',
        cost=3,
        placeholder='Например: каталог мебели с ценой, категорией, '
                    'фотографией и остатком на складе.',
        needs_description=True,
        instruction=(
            'Предложи схему данных по описанию задачи. Верни JSON-объект '
            'с полями summary и items — массив полей. В каждом элементе: '
            'key — машинное имя латиницей, label — подпись по-русски, '
            'type — одно из text, number, boolean, date, image, link '
            '(типы узлов данных платформы), required: true для полей, '
            'без которых запись бессмысленна, detail — зачем поле. '
            'Не добавляй поля «на всякий случай».'
        ),
    ),
    'project_review': Action(
        code='project_review',
        title='Разбор проекта',
        description='Короткая проверка собранного: что уже есть и какой '
                    'шаг логичнее сделать дальше.',
        cost=1,
        placeholder='',
        needs_description=False,
        instruction=(
            'Посмотри на сводку проекта (число страниц, записей, '
            'публикация) и предложи 2–4 следующих шага. Верни JSON-объект '
            'с полями summary и items. В каждом элементе: title — шаг, '
            'detail — почему он сейчас полезен. Не пересказывай сводку '
            'и не выдумывай данные, которых в ней нет.'
        ),
    ),
}

ACTION_LIST = tuple(ACTIONS.values())

#: Пределы описания. Нижняя граница отсекает «сделай красиво», на
#: которую нельзя ответить по существу; верхняя защищает от того, что
#: в промпт случайно вставили весь документ.
MIN_DESCRIPTION = 10
MAX_DESCRIPTION = 1500


def get_action(code: str) -> Action | None:
    return ACTIONS.get((code or '').strip())


__all__ = [
    'ACTIONS',
    'ACTION_LIST',
    'MAX_DESCRIPTION',
    'MIN_DESCRIPTION',
    'Action',
    'get_action',
]
