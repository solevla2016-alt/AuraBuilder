LESSONS_BY_ID = {lesson['id']: lesson for lesson in LESSONS}


def lesson_public(lesson: dict, completed_at=None) -> dict:
    """Урок в форме ответа API.

    Прогресс передаётся отметкой, а не вычисляется здесь: урок ничего не
    знает о пользователе, и это позволяет держать содержание общим.
    """

    return {
        'id': lesson['id'],
        'track': lesson['track'],
        'title': lesson['title'],
        'summary': lesson['summary'],
        'minutes': lesson['minutes'],
        'steps': list(lesson['steps']),
        'completed': completed_at is not None,
        'completedAt': completed_at.isoformat() if completed_at else None,
    }
