def _channels(hex_color: str) -> tuple[float, float, float]:
    value = hex_color.lstrip('#')
    return tuple(int(value[i : i + 2], 16) / 255 for i in (0, 2, 4))  # type: ignore[return-value]


def relative_luminance(hex_color: str) -> float:
    """РћС‚РЅРѕСЃРёС‚РµР»СЊРЅР°СЏ СЏСЂРєРѕСЃС‚СЊ С†РІРµС‚Р° РїРѕ WCAG 2.1."""

    def channel(c: float) -> float:
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (channel(c) for c in _channels(hex_color))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_ratio(foreground: str, background: str) -> float:
    """РљРѕРЅС‚СЂР°СЃС‚ РґРІСѓС… РЅРµРїСЂРѕР·СЂР°С‡РЅС‹С… С†РІРµС‚РѕРІ."""

    first = relative_luminance(foreground)
    second = relative_luminance(background)
    lighter, darker = max(first, second), min(first, second)
    return round((lighter + 0.05) / (darker + 0.05), 2)


