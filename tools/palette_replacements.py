def main() -> int:
    if not DOCX.exists():
        print(f'not found: {DOCX}')
        return 1

    failed = 0
    for old, new in REPL:
        r = subprocess.run(
            [sys.executable, str(TZE), 'replace', str(DOCX), old, new],
            capture_output=True, text=True, encoding='utf-8',
        )
        out = (r.stdout or '').strip()
        n = out.replace('replaced in ', '').replace(' paragraphs', '').strip()
        ok = n.isdigit() and int(n) > 0
        if not ok:
            failed += 1
        print(('OK  ' if ok else '!!  ') + f'{n:>3s}  {old[:62]}')

    print()
    print(f'всего замен: {len(REPL)}, не сработало: {failed}')
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())