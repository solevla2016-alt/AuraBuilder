import subprocess
import sys

DOCX, TZE = sys.argv[1], sys.argv[2]

REPL = [
    ('Стоимость для пользователя: Включено в подписку (от 500 ₽/мес)',
     'Стоимость для пользователя: включено в подписку. Публикация на поддомене mysite.aurabuilder.ru — тариф Free; на своём домене — от тарифа Start (см. п.17.1)'),
    ('Стоимость для пользователя: Доступно на тарифах от 1500 ₽/мес',
     'Стоимость для пользователя: от тарифа Start (см. п.17.1)'),
    ('Стоимость для пользователя: Доступно на тарифах от 2000 ₽/мес',
     'Стоимость для пользователя: от тарифа Pro (см. п.17.1)'),
    ('Стоимость для пользователя: Доступно на всех тарифах (включая бесплатный)',
     'Стоимость для пользователя: доступно на всех тарифах, включая Free'),
]

for old, new in REPL:
    r = subprocess.run([sys.executable, TZE, 'replace', DOCX, old, new],
                       capture_output=True, text=True, encoding='utf-8')
    out = (r.stdout or '').strip()
    print(('OK ' if 'replaced in' in out and ' 0 ' not in out else '!! ') + out[:60] + '  ' + old[:50])
